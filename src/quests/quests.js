// Шаги многошагового квеста (пустой массив для обычного квеста)
export function questSteps(quest) {
  return quest.steps ?? [];
}

export function stepAt(quest, index) {
  return questSteps(quest)[index] ?? null;
}

export function fillTemplate(text, name) {
  return text.replaceAll('{name}', name);
}
