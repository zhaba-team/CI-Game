// Описание квестов. Чтобы добавить новый квест:
// 1) создайте мини-игру в src/minigames и зарегистрируйте её в src/minigames/index.js;
// 2) добавьте запись сюда (npc — id из npcs.js, spot — точка из office.js).
// В текстах можно использовать {name} — подставится никнейм игрока.
//
// Многошаговый квест (сюжет после принятия) описывается массивом steps вместо minigame/spot.
// Шаги идут строго по порядку; после последнего квест выполнен. Схема шага:
//   { id, type: 'talk' | 'pickup' | 'hazard' | 'minigame' | 'screen', where, hint?, spot?, npc?, lines?,
//     action?, minigame?, item?, targets?, need?, serverDown?, brokenScreen?, toast?, alarm?,
//     approach?, screen?, duration? }
//   talk     — маркер на spot; диалог npc со строками lines, последняя кнопка action завершает шаг;
//              E на самом NPC открывает тот же диалог;
//              approach: true — маркера нет: NPC сам идёт к игроку по маршруту office.spots[spot].path
//              до точки spot, диалог открывается автоматически; после диалога NPC возвращается на место;
//   pickup   — маркер на spot; при наступании игрок получает предмет item, шаг завершён;
//   hazard   — цели targets (ключи office.spots с полем rack); у каждой — действие action, если в руках item
//              (он в руках, пока шаг текущий); need — подсказка у цели, пока предмета ещё нет;
//              шаг завершён, когда выполнены все цели;
//   minigame — как обычный квест: маркер на spot и мини-игра minigame (задание от npc ?? quest.npc);
//   screen   — полноэкранная сцена из реестра ui/screens.js (screen: 'bsod'), без маркера:
//              начинается, как только шаг становится текущим, и заканчивается сама через duration секунд.
// Общие поля: where / hint — подсказка в журнале («Иди: where» или hint как есть);
// toast — уведомление, когда шаг становится текущим (alarm: true — тревожный стиль и вспышка экрана);
// serverDown: true — пока шаг текущий, серверная «лежит» (красные лампочки и свет);
// brokenScreen: '<ключ office.spots рабочего места>' — пока шаг текущий, монитор этого стола показывает синий экран.
